"""Translation sums Q = sum_x q_x of h-words as site-independent MPOs in the spin basis (for the iMPS code).

With n_k the occupation of word k, an ordered product h_S = prod_{s in S} h_s (h_j = Z_j Z_{j+1} X_{j+2}) is the
Pauli string prod_k X^{n_{k-2}} Z^{n_{k-1} xor n_k}, without a phase.  A word with first word f and last word s
therefore acts on the spins f .. s + 2, and an operator whose word coefficients are generated by an automaton on the
occupation string is an MPO whose bond state is the automaton state (each state fixes the last two occupations).

Form used throughout: state 0 = IDLE (no word in progress, identity); the other states are inside a word.  W0 holds
the transitions that do not complete a word, W1 the transitions that complete one (into IDLE, at the spin s + 2).
With a weight mu on W1, prod_x (W0 + mu W1) generates sum_k mu^k (all sets of k separated words); its term linear in
mu is Q.  Tensors have shape (D, D, 2, 2) = [left state, right state, out spin, in spin].
"""
import numpy as np

from ..model import pattern
from .charges import _block_rules
from .wordmpo import _sort_word

_I2 = np.eye(2)
_X = np.array([[0., 1.], [1., 0.]])
_Z = np.diag([1., -1.])
_PAULI = {(0, 0): _I2, (0, 1): _Z, (1, 0): _X, (1, 1): _X @ _Z}       # X^a Z^b


class SumMPO:
    """translation sum in IDLE form: W0 (no word completed), W1 (a word completed at this spin)"""

    def __init__(self, W0, W1, name=''):
        self.W0, self.W1, self.name = W0, W1, name

    @property
    def D(self):
        return self.W0.shape[0]

    @classmethod
    def identity(cls):
        return cls(_I2[None, None].astype(complex), np.zeros((1, 1, 2, 2), complex), 'I')

    @classmethod
    def from_automaton(cls, hist, trans, name=''):
        """hist[i] = (n_{k-1}, n_k) after entering state i; trans = [(i, n, j, weight, completes_word)]"""
        D = len(hist)
        W = np.zeros((2, D, D, 2, 2), complex)
        for i, n, j, w, end in trans:
            a, b = hist[i]
            if hist[j] != (b, n):
                raise ValueError(f'inconsistent automaton: state {j} entered from {i} with n = {n}')
            W[int(end), i, j] += w * _PAULI[(a, b ^ n)]
        return cls(W[0], W[1], name)


def charge_mpo(family, p, parity, name=''):
    """Q^{a,+-}_p (parity +1 / -1: words of even / odd size; 0: all words), coefficients as in qlc.tn.charges.

    States: IDLE, then (B1, B2, GAP) = first site of a block, later site of a block, the empty site after a block,
    once for each sign eta of the occupation weight; the parity part is (Q[eta = 1] + parity Q[eta = -1]) / 2."""
    w1, w2, s_ext = _block_rules(family, p)
    copies = ((1, 1.0),) if parity == 0 else ((1, 0.5), (-1, 0.5 * parity))
    hist = [(0, 0)]
    trans = [(0, 0, 0, 1, False)]
    for eta, f in copies:
        b1, b2, gap = len(hist), len(hist) + 1, len(hist) + 2
        hist += [(0, 1), (1, 1), (1, 0)]
        trans += [(0, 1, b1, 1j * eta * f, False), (b1, 1, b2, eta, False), (b2, 0, gap, w2, False),
                  (gap, 1, b1, eta, False), (gap, 0, 0, 1, True)]
        if w1 is not None:
            trans.append((b1, 0, gap, w1, False))
        if s_ext is not None:
            trans.append((b2, 1, b2, eta * s_ext, False))
    return SumMPO.from_automaton(hist, trans, name or f'{family}{"+-"[parity < 0] if parity else ""}({p:g})')


def pattern_mpo(pat, name=''):
    """sum_x sum_P c_P h_{x+P} for a pattern (dict of offsets -> coefficient, ordered products) as a trie MPO: one state
    per prefix of the occupation strings, one shared tail state (the empty word after the last one)"""
    words = {}
    for offs, c in pattern(pat).items():
        lo = min(offs)
        sign, S = _sort_word([o - lo for o in offs])
        bits = tuple(int(k in S) for k in range(S[-1] + 1))
        words[bits] = words.get(bits, 0) + sign * c
    node = {(): 0}
    hist = [(0, 0)]
    trans = [(0, 0, 0, 1, False)]
    for bits in sorted(words):
        for k in range(1, len(bits) + 1):
            pre = bits[:k]
            if pre not in node:
                node[pre] = len(hist)
                hist.append(((0, 0) + pre)[-2:])
                trans.append((node[pre[:-1]], pre[-1], node[pre], 1, False))
    tail = len(hist)
    hist.append((1, 0))
    trans += [(node[bits], 0, tail, c, False) for bits, c in words.items() if c != 0]
    trans.append((tail, 0, 0, 1, True))
    return SumMPO.from_automaton(hist, trans, name or (pat if isinstance(pat, str) else 'pattern'))
